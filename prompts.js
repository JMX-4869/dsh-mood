/** 出厂的那 27 组。键是「高/中/低」的组合，值是 { n, combo, state, lang, taboo }。 */
export function defaultPrompts() {
  const out = {}
  RAW.forEach(([k, state, lang, taboo], i) => {
    const key = symbolicKey(k)
    out[key] = { n: i + 1, combo: key.replace(/\//g, '／'), state, lang, taboo }
  })
  return out
}

/** 三维的定义（面板和注入都靠它，顺序不能乱）。 */
export const DIMENSIONS = [
  { key: 'affection', name: '好感度', target: '你' },
  { key: 'disappointment', name: '失望度', target: '事' },
  { key: 'selfEsteem', name: '自我肯定', target: '我' },
]

/** 数值 → 档位（'高' / '中' / '低'）。阈值可调，档位固定三档。 */
export function levelOf(value, thresholds) {
  const high = Number(thresholds && thresholds.high) || 50
  const low = Number(thresholds && thresholds.low) || -50
  const v = Number(value) || 0
  if (v >= high) return '高'
  if (v <= low) return '低'
  return '中'
}

/** 三维值 → 27 组里的那个键。 */
export function promptKeyOf(dims, thresholds) {
  return DIMENSIONS.map((d) => levelOf(dims && dims[d.key], thresholds)).join('/')
}
