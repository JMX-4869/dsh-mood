//
// 三维：好感度（对「你」）/ 失望度（对「事」，反向）/ 自我肯定（对「我」）。
// 每维三档（高 / 中 / 低），3³ = 27 组，每组给三句话：
//   state  —— 这是什么状态（给人看的，也进注入）
//   lang   —— 怎么说话（真正干预输出的那句）
//   taboo  —— 别做什么
//
// 键用**符号**（高/中/低），不用数字：阈值从 ±50 改成 ±30，键还是这 27 个，不失效。

/** 数字档 → 符号档。100 → 高，0 → 中，−100 → 低。 */
export function symbolicKey(numericKey) {
  return String(numericKey)
    .split('/')
    .map((v) => {
      const n = Number(v)
      if (!Number.isFinite(n) || n === 0) return '中'
      return n > 0 ? '高' : '低'
    })
    .join('/')
}

